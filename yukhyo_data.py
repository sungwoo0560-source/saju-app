_JJ12 = ("子", "丑", "寅", "卯", "辰", "巳", "午", "未", "申", "酉", "戌", "亥")
_ILJIN_REF_DATE = _date(2000, 1, 1)   # 2000-01-01 = 戊午日(60갑자 순번 54, 甲子=0)
_ILJIN_REF_IDX = 54


def get_ilju(target_date=None):
    """점치는 날의 일진(日辰)을 60갑자로 자체 계산 — 천간+지지 문자열 반환.
    target_date가 None이면 오늘(datetime.date.today())을 쓴다."""
    if target_date is None:
        target_date = _date.today()
    _delta = (target_date - _ILJIN_REF_DATE).days
    _idx = (_ILJIN_REF_IDX + _delta) % 60
    return _CG10[_idx % 10] + _JJ12[_idx % 12]


