# 사주 신살과는 독립된 규칙. saju_sinsal.py에 이미 YANGIN_MAP 등 동일
# 계열 전역명이 있어(`from ... import *` 순서상 나중에 import되는 쪽이
# 덮어씀 — get_yukhyo_gongmang과 같은 이유로 실제 사고가 났던 패턴이라
# 전부 YUKHYO_ 접두를 붙여 분리한다. 육효는 연주·월주가 없고 그날의
# 일진(日辰) 하나만 기준으로 삼는다(사주처럼 연지·일간 각각 기준이
# 갈리지 않음).

# 역마(驛馬)·도화(桃花, 咸池) — 지지 삼합 4국(申子辰·亥卯未·寅午戌·
# 巳酉丑, 기존 SAMHAP_JIGUK과 동일 4국)에서 파생되는 통용 구결표.
# "申子辰見寅‥" 역마 구결, "寅午戌兔卯裏出‥" 도화 구결과 손검산 일치.
YUKHYO_YEOKMA = {
    frozenset({"申", "子", "辰"}): "寅",
    frozenset({"寅", "午", "戌"}): "申",
    frozenset({"巳", "酉", "丑"}): "亥",
    frozenset({"亥", "卯", "未"}): "巳",
}
YUKHYO_DOHWA = {
    frozenset({"申", "子", "辰"}): "酉",
    frozenset({"寅", "午", "戌"}): "卯",
    frozenset({"巳", "酉", "丑"}): "午",
    frozenset({"亥", "卯", "未"}): "子",
}

# 양인(羊刃)·천을귀인(天乙貴人) — 일간(日干) 기준 통용표.
# 양인: 甲卯乙辰丙午丁未戊午己未庚酉辛戌壬子癸丑.
# 천을귀인 구결 "甲戊庚牛羊·乙己鼠猴鄉·丙丁豬雞位·壬癸兔蛇藏·六辛逢馬虎"와 손검산 일치.
YUKHYO_YANGIN = {
    "甲": "卯", "乙": "辰", "丙": "午", "丁": "未", "戊": "午",
    "己": "未", "庚": "酉", "辛": "戌", "壬": "子", "癸": "丑",
}
YUKHYO_CHEONEUL = {
    "甲": ("丑", "未"), "戊": ("丑", "未"), "庚": ("丑", "未"),
    "乙": ("子", "申"), "己": ("子", "申"),
    "丙": ("亥", "酉"), "丁": ("亥", "酉"),
    "壬": ("巳", "卯"), "癸": ("巳", "卯"),
    "辛": ("午", "寅"),
}


def get_yukhyo_sinsal_targets(ilju):
    """점친 날 일진(60갑자 문자열, 예: '甲子')에서 역마·도화·양인·
    천을귀인의 지지를 구한다. 12지지는 정확히 3개씩 4국으로 나뉘므로
    역마·도화는 항상 어느 한 국에 걸린다(전수 커버, 예외 없음).
    반환: {"역마": 지지, "도화": 지지, "양인": 지지,
    "천을귀인": (지지1, 지지2)}."""
    _cg, _jj = ilju[0], ilju[1]
    _yeokma = next(_v for _k, _v in YUKHYO_YEOKMA.items() if _jj in _k)
    _dohwa = next(_v for _k, _v in YUKHYO_DOHWA.items() if _jj in _k)
    return {
        "역마": _yeokma,
        "도화": _dohwa,
        "양인": YUKHYO_YANGIN[_cg],
        "천을귀인": YUKHYO_CHEONEUL[_cg],
    }


def tag_yukhyo_sinsal(jiji, sinsal_targets):
    """지지 하나가 해당하는 신살 이름 목록을 반환(0~여러 개 겹칠 수 있음)."""
    _tags = []
    if jiji == sinsal_targets["역마"]:
        _tags.append("역마")
    if jiji == sinsal_targets["도화"]:
        _tags.append("도화")
    if jiji == sinsal_targets["양인"]:
        _tags.append("양인")
    if jiji in sinsal_targets["천을귀인"]:
        _tags.append("천을귀인")
    return _tags


_YUKHYO_SINSAL_PHRASE = {
    "역마": "역마(驛馬)의 기운도 걸려 있어 이동이나 변동의 조짐이 함께 나타납니다.",
    "도화": "도화(桃花)의 기운이 함께 있어 사람 사이의 관심이나 매력이 얽힌 자리이기도 합니다.",
    "양인": "양인(羊刃)의 기운이 걸려 있어 다툼이나 무리한 힘겨루기는 삼가는 것이 좋겠습니다.",
    "천을귀인": "천을귀인(天乙貴人)의 기운도 함께 있어 뜻밖의 도움을 받을 가능성이 있습니다.",
}

