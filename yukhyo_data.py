def get_yukchin(gung_ohang, hyo_ohang):
    """육친(六親) 배속 — 궁(宮)의 오행과 효(爻) 지지의 오행이 맺는 생극으로 결정.
    생아자(生我者, 효가 궁을 생함)=부모 · 아생자(我生者, 궁이 효를 생함)=자손 ·
    극아자(剋我者, 효가 궁을 극함)=관귀 · 아극자(我剋者, 궁이 효를 극함)=처재 ·
    동아자(同我者, 오행이 같음)=형제. gung_ohang·hyo_ohang은 '金水木火土' 중 하나."""
    if hyo_ohang == gung_ohang:
        return "형제"
    if _OHANG_SAENG[hyo_ohang] == gung_ohang:
        return "부모"
    if _OHANG_SAENG[gung_ohang] == hyo_ohang:
        return "자손"
    if _OHANG_GEUK[hyo_ohang] == gung_ohang:
        return "관귀"
    if _OHANG_GEUK[gung_ohang] == hyo_ohang:
        return "처재"
    raise ValueError(f"오행 생극표에 없는 조합: 궁={gung_ohang}, 효={hyo_ohang}")


